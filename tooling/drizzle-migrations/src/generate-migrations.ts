import { generateSQLiteDrizzleJson } from "drizzle-kit/api";
import childProcess from "node:child_process";
import fs from "node:fs/promises";
import path from "node:path";
import url from "node:url";

type Journal = { entries: { idx: number; tag: string }[] };
type Snapshot = { id: string; prevId: string };

/**
 * Generates SQLite migrations for each store from its schema files under `src/`, then bundles the
 * journal and SQL into `src/migrations/<store>.ts`. Runs in the current package directory and
 * passes `args` to `drizzle-kit generate`.
 */
export async function generateMigrations(
  stores: Record<string, string[]>,
  args: string[] = process.argv.slice(2),
): Promise<void> {
  const isCustomMigration = args.includes("--custom");
  for (const [store, schemaFiles] of Object.entries(stores)) {
    childProcess.execFileSync(
      "pnpm",
      [
        "exec",
        "drizzle-kit",
        "generate",
        "--dialect",
        "sqlite",
        "--schema",
        schemaFiles.length === 1 ? `./src/${schemaFiles[0]}` : `./src/{${schemaFiles.join(",")}}`,
        "--out",
        `./drizzle/${store}`,
        ...args,
      ],
      { stdio: "inherit" },
    );
    const journal: Journal = JSON.parse(
      await fs.readFile(`drizzle/${store}/meta/_journal.json`, "utf8"),
    );
    const lastEntry = journal.entries.at(-1);
    if (isCustomMigration && lastEntry) {
      await writeCurrentSnapshot(store, schemaFiles, lastEntry.idx);
    }
    const migrations: Record<string, string> = {};
    for (const entry of journal.entries) {
      migrations[`m${String(entry.idx).padStart(4, "0")}`] = await fs.readFile(
        `drizzle/${store}/${entry.tag}.sql`,
        "utf8",
      );
    }
    await fs.mkdir("src/migrations", { recursive: true });
    await fs.writeFile(
      `src/migrations/${store}.ts`,
      `// Generated by migrations:generate. Edit schemas and generate a new migration.\nexport default ${JSON.stringify({ journal, migrations }, null, 2)};\n`,
    );
  }
  childProcess.execFileSync("pnpm", ["exec", "oxfmt", "src/migrations", "drizzle"], {
    stdio: "inherit",
  });
}

/**
 * Drizzle Kit gives a custom migration a copy of the previous snapshot. The handwritten SQL must
 * produce the current schema, so record that schema as the snapshot for later diffs.
 */
async function writeCurrentSnapshot(store: string, schemaFiles: string[], idx: number) {
  const snapshotPath = `drizzle/${store}/meta/${String(idx).padStart(4, "0")}_snapshot.json`;
  const copied: Snapshot = JSON.parse(await fs.readFile(snapshotPath, "utf8"));
  const schema: Record<string, unknown> = {};
  for (const file of schemaFiles) {
    Object.assign(schema, await import(url.pathToFileURL(path.resolve("src", file)).href));
  }
  const {
    version,
    dialect,
    id: _id,
    prevId: _prevId,
    ...current
  } = await generateSQLiteDrizzleJson(schema, copied.prevId);
  await fs.writeFile(
    snapshotPath,
    JSON.stringify({ version, dialect, id: copied.id, prevId: copied.prevId, ...current }, null, 2),
  );
}
