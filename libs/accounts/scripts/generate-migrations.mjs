import childProcess from "node:child_process";
import fs from "node:fs/promises";

const stores = {
  account: "{account-sqlite-schema,sqlite-schema-shared}.ts",
};

for (const [store, schema] of Object.entries(stores)) {
  childProcess.execFileSync(
    "pnpm",
    [
      "exec",
      "drizzle-kit",
      "generate",
      "--dialect",
      "sqlite",
      "--schema",
      `./src/${schema}`,
      "--out",
      `./drizzle/${store}`,
      ...process.argv.slice(2),
    ],
    { stdio: "inherit" },
  );
  const journal = JSON.parse(await fs.readFile(`drizzle/${store}/meta/_journal.json`, "utf8"));
  const migrations = {};
  for (const entry of journal.entries) {
    migrations[`m${String(entry.idx).padStart(4, "0")}`] = await fs.readFile(
      `drizzle/${store}/${entry.tag}.sql`,
      "utf8",
    );
  }
  await fs.mkdir("src/migrations", { recursive: true });
  await fs.writeFile(
    `src/migrations/${store}.ts`,
    `// Generated by migrations:generate. Edit schemas and generate a new migration.\nexport default ${JSON.stringify({ journal, migrations }, null, 2)};\n`,
  );
}
childProcess.execFileSync("pnpm", ["exec", "oxfmt", "src/migrations", "drizzle"], {
  stdio: "inherit",
});
